import type { Recipe, RecipeCost } from "../types";

type Ing = [name: string, quantity: number, unit: "г" | "мл" | "шт", pricePerUnit: number];

type Raw = {
  id: string;
  name: string;
  department: string;
  section: string;
  category: string;
  time: string;
  portions: number;
  yield: string;
  description: string;
  ingredients: Ing[];
  steps: string[];
  tags: string[];
  popular?: boolean;
};

const fmt = new Intl.NumberFormat("ru-RU", { maximumFractionDigits: 2 });

function buildCost(ings: Ing[], portions: number): RecipeCost {
  const lines = ings.map(([name, quantity, unit, pricePerUnit]) => ({
    name,
    quantity,
    unit,
    pricePerUnit,
    total: Math.round(quantity * pricePerUnit)
  }));
  const total = lines.reduce((s, l) => s + l.total, 0);
  return {
    total,
    perPortion: portions > 0 ? Math.round(total / portions) : null,
    portions,
    complete: true,
    lines
  };
}

